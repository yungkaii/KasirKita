import { AsyncLocalStorage } from 'node:async_hooks'
import { Pool, type PoolClient, type QueryResultRow } from 'pg'
import bcrypt from 'bcryptjs'

const connectionString = process.env.DATABASE_URL
if (!connectionString) throw new Error('DATABASE_URL wajib diisi untuk koneksi Supabase Postgres.')

const pool = new Pool({ connectionString, ssl: { rejectUnauthorized: false }, max: 5 })
const transactionStore = new AsyncLocalStorage<PoolClient>()

const placeholders = (sql: string) => {
  let index = 0
  return sql.replace(/\?/g, () => `$${++index}`)
}

type Statement = {
  get: (...params: unknown[]) => Promise<QueryResultRow | undefined>
  all: (...params: unknown[]) => Promise<QueryResultRow[]>
  run: (...params: unknown[]) => Promise<{ changes: number; lastInsertRowid: number | undefined }>
}

const prepare = (sql: string): Statement => ({
  async get(...params) { return (await query(sql, params)).rows[0] },
  async all(...params) { return (await query(sql, params)).rows },
  async run(...params) {
    const result = await query(sql, params)
    return { changes: result.rowCount || 0, lastInsertRowid: result.rows[0]?.id as number | undefined }
  },
})

async function query(sql: string, params: unknown[] = []) {
  const client = transactionStore.getStore()
  return client ? client.query(placeholders(sql), params) : pool.query(placeholders(sql), params)
}

export const db = {
  prepare,
  async transaction<T>(callback: () => Promise<T>) {
    const client = await pool.connect()
    try {
      await client.query('BEGIN')
      const result = await transactionStore.run(client, callback)
      await client.query('COMMIT')
      return result
    } catch (error) {
      await client.query('ROLLBACK')
      throw error
    } finally { client.release() }
  },
}

