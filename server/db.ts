export async function seedDatabase() {
  const count = await db.prepare('SELECT COUNT(*) AS count FROM users').get() as { count: string }
  if (Number(count.count) === 0) {
    const adminPassword = process.env.SEED_ADMIN_PASSWORD
    const cashierPassword = process.env.SEED_CASHIER_PASSWORD
    if (!adminPassword || !cashierPassword) throw new Error('Database kosong. Isi SEED_ADMIN_PASSWORD dan SEED_CASHIER_PASSWORD di environment variables.')
    await db.prepare('INSERT INTO users(username, password_hash, display_name, role) VALUES (?, ?, ?, ?)').run(process.env.SEED_ADMIN_USERNAME || 'owner', bcrypt.hashSync(adminPassword, 12), process.env.SEED_ADMIN_NAME || 'Pemilik Toko', 'admin')
    await db.prepare('INSERT INTO users(username, password_hash, display_name, role) VALUES (?, ?, ?, ?)').run(process.env.SEED_CASHIER_USERNAME || 'kasir', bcrypt.hashSync(cashierPassword, 12), process.env.SEED_CASHIER_NAME || 'Kasir Utama', 'kasir')
  }
  await db.prepare('INSERT INTO settings(key, value) VALUES (?, ?) ON CONFLICT(key) DO NOTHING').run('storeName', process.env.STORE_NAME || 'KasirKita')
  await db.prepare('INSERT INTO settings(key, value) VALUES (?, ?) ON CONFLICT(key) DO NOTHING').run('taxRate', process.env.DEFAULT_TAX_RATE || '11')
  const categoryCount = await db.prepare('SELECT COUNT(*) AS count FROM categories').get() as { count: string }
  if (Number(categoryCount.count) === 0) for (const name of ['Makanan', 'Minuman', 'Camilan']) await db.prepare('INSERT INTO categories(name) VALUES (?)').run(name)
}
